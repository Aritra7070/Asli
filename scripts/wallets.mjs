#!/usr/bin/env node
// Asli — demo signer generator.
//
// Generates throwaway Tiramisu-testnet signers and writes their PRIVATE KEYS
// ONLY to .env.local (git-ignored). Safe to re-run: existing keys are kept,
// only missing ones are added. Only public addresses are printed.
//
// Usage: npm run wallets:new

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { privateKeyToAccount } from "viem/accounts";

const ENV_PATH = ".env.local";

const ROLES = [
  { env: "ASLI_MFR_PRIVATE_KEY", label: "MFR", name: "Aushadh Labs (synthetic manufacturer)", city: "Hyderabad" },
  { env: "ASLI_DIST_PRIVATE_KEY", label: "DIST", name: "MedRoute Logistics (synthetic distributor)", city: "Mumbai" },
  { env: "ASLI_RELIANT_PRIVATE_KEY", label: "RELIANT", name: "Reliant Pharmacy", city: "Pune" },
  { env: "ASLI_QM_PRIVATE_KEY", label: "QM", name: "QuickMeds Hub (quick-commerce dark store)", city: "Gurugram" },
  { env: "ASLI_RELAY_PRIVATE_KEY", label: "RELAY", name: "Asli Scan Relay (public patient scans)", city: "—" },
  { env: "ASLI_FAKE_PRIVATE_KEY", label: "FAKE", name: "Unregistered seller (demo counterfeiter)", city: "—" },
];

let content = existsSync(ENV_PATH) ? readFileSync(ENV_PATH, "utf8") : "";
const header =
  "# Asli — throwaway TESTNET signers (generated by scripts/wallets.mjs).\n" +
  "# Never commit this file. Keys sign synthetic demo data on Tiramisu only.\n";

if (!content) content = header;

const rows = [];

for (const role of ROLES) {
  const existing = content.match(new RegExp(`^${role.env}=(\\S+)`, "m"));
  if (existing) {
    const account = privateKeyToAccount(existing[1].trim());
    rows.push({ ...role, address: account.address, created: false });
  } else {
    const pk = "0x" + randomBytes(32).toString("hex");
    const account = privateKeyToAccount(pk);
    content += `${role.env}=${pk}\n`;
    rows.push({ ...role, address: account.address, created: true });
  }
}

if (!content.endsWith("\n")) content += "\n";
writeFileSync(ENV_PATH, content, "utf8");

console.log("");
console.log("Asli demo signers (private keys written to .env.local — never share or commit that file)");
console.log("=".repeat(100));
for (const r of rows) {
  const tag = r.created ? "NEW" : "kept";
  console.log(`${r.label.padEnd(9)} ${r.address}`);
  console.log(`${" ".repeat(9)} ${r.name}${r.city === "—" ? "" : ", " + r.city}  [${tag}]`);
}
console.log("=".repeat(100));
console.log("");
console.log("Next steps:");
console.log("  1. Fund these 6 addresses with testnet GLM (they pay gas for the demo writes).");
console.log("     Easiest: paste your burner key into FUNDER_PRIVATE_KEY in .env.local, then run:");
console.log("        npm run wallets:fund");
console.log("     Then fund your burner from the faucet if you haven't:");
console.log("        https://hub.arkiv.network/faucet");
console.log("  2. Run the seed to create the first Arkiv entities:");
console.log("        npm run seed");
